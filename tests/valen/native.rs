fn png_url(width: u32, height: u32, colour: [u8; 3]) -> String {
    image_url(&png_bytes(width, height, colour))
}

fn jpeg_url(width: u32, height: u32, colour: [u8; 3]) -> String {
    let image = image::RgbImage::from_pixel(width, height, image::Rgb(colour));
    let mut bytes = Vec::new();
    image
        .write_to(&mut Cursor::new(&mut bytes), image::ImageFormat::Jpeg)
        .unwrap();
    format!(
        "data:image/jpeg;base64,{}",
        base64::engine::general_purpose::STANDARD.encode(bytes)
    )
}

fn png_bytes(width: u32, height: u32, colour: [u8; 3]) -> Vec<u8> {
    let image = image::RgbImage::from_pixel(width, height, image::Rgb(colour));
    let mut bytes = Vec::new();
    image
        .write_to(&mut Cursor::new(&mut bytes), image::ImageFormat::Png)
        .unwrap();
    bytes
}

fn crc32(data: &[u8]) -> u32 {
    let mut crc = !0u32;
    for &byte in data {
        crc ^= u32::from(byte);
        for _ in 0..8 {
            crc = if crc & 1 != 0 {
                (crc >> 1) ^ 0xEDB8_8320
            } else {
                crc >> 1
            };
        }
    }
    !crc
}

/// One PNG chunk: big-endian length, type, data, CRC.
fn png_chunk(kind: &[u8; 4], data: &[u8]) -> Vec<u8> {
    let mut chunk = (data.len() as u32).to_be_bytes().to_vec();
    chunk.extend_from_slice(kind);
    chunk.extend_from_slice(data);
    let crc = crc32(&chunk[4..]);
    chunk.extend_from_slice(&crc.to_be_bytes());
    chunk
}

/// Extra chunks spliced after the first chunk of `kind`, keeping the rest of
/// the encoded PNG (and its CRCs) untouched.
fn png_splice_after(png: &[u8], kind: &[u8; 4], extras: &[Vec<u8>]) -> Vec<u8> {
    let mut at = 8;
    let mut split = png.len();
    while at + 8 <= png.len() {
        let length = u32::from_be_bytes([png[at], png[at + 1], png[at + 2], png[at + 3]]) as usize;
        if &png[at + 4..at + 8] == kind {
            split = at + 12 + length;
            break;
        }
        at += 12 + length;
    }
    let mut out = png[..split].to_vec();
    for extra in extras {
        out.extend_from_slice(extra);
    }
    out.extend_from_slice(&png[split..]);
    out
}

/// An `acTL` animation chunk declaring `num_frames` and zero plays — the
/// eight bytes PIL's chunk handler requires.
fn actl(num_frames: u32) -> Vec<u8> {
    let mut data = num_frames.to_be_bytes().to_vec();
    data.extend_from_slice(&0u32.to_be_bytes()); // num_plays
    png_chunk(b"acTL", &data)
}

/// A first-frame `fcTL` for the base image's geometry.
fn fctl(width: u32, height: u32) -> Vec<u8> {
    let mut data = Vec::new();
    data.extend_from_slice(&0u32.to_be_bytes()); // sequence number
    data.extend_from_slice(&width.to_be_bytes());
    data.extend_from_slice(&height.to_be_bytes());
    data.extend_from_slice(&0u32.to_be_bytes()); // x offset
    data.extend_from_slice(&0u32.to_be_bytes()); // y offset
    data.extend_from_slice(&1u16.to_be_bytes()); // delay numerator
    data.extend_from_slice(&100u16.to_be_bytes()); // delay denominator
    data.push(0); // dispose op
    data.push(0); // blend op
    png_chunk(b"fcTL", &data)
}

fn image_url(png: &[u8]) -> String {
    format!(
        "data:image/png;base64,{}",
        base64::engine::general_purpose::STANDARD.encode(png)
    )
}

/// A case's request bytes: the recorded body, with generated images (only the
/// dimensions matter to the layout) regenerated by this side's encoder.
fn case_body(case: &Value) -> Vec<u8> {
    let mut body: Value = serde_json::from_str(case["body"].as_str().unwrap()).unwrap();
    if let Some(image) = case.get("image")
        && image["kind"] == "generated"
    {
        let size = image["size"].as_array().unwrap();
        let colour = image["colour"].as_array().unwrap();
        let rgb = [0, 1, 2].map(|i| colour[i].as_u64().unwrap() as u8);
        let url = if image["format"] == "png" {
            png_url(
                size[0].as_u64().unwrap() as u32,
                size[1].as_u64().unwrap() as u32,
                rgb,
            )
        } else {
            jpeg_url(
                size[0].as_u64().unwrap() as u32,
                size[1].as_u64().unwrap() as u32,
                rgb,
            )
        };
        body["state"]["image"] = Value::String(url);
        return serde_json::to_vec(&body).unwrap();
    }
    case["body"].as_str().unwrap().as_bytes().to_vec()
}

/// A rejection entry's request bytes.
fn rejection_body(entry: &Value) -> Vec<u8> {
    if let Some(encoded) = entry.get("body_b64") {
        return base64::engine::general_purpose::STANDARD
            .decode(encoded.as_str().unwrap())
            .unwrap();
    }
    match entry.get("synthesize").and_then(Value::as_str) {
        Some("body_oversize") => {
            let question = serde_json::json!({
                "type": "choice", "instructions": "Pick.", "criteria": {"a": "b"}
            });
            let body = serde_json::json!({
                "model": "valen-preview-0923",
                "state": "A".repeat(8 * 1024 * 1024 + 64),
                "questions": {"q": question},
            });
            serde_json::to_vec(&body).unwrap()
        }
        Some("image_encoded_oversize") => {
            let question = serde_json::json!({
                "type": "choice", "instructions": "Pick.", "criteria": {"a": "b"}
            });
            let encoded = "A".repeat(4 * (4usize * 1024 * 1024).div_ceil(3) + 1);
            let body = serde_json::json!({
                "model": "valen-preview-0923",
                "state": {"image": format!("data:image/png;base64,{encoded}")},
                "questions": {"q": question},
            });
            serde_json::to_vec(&body).unwrap()
        }
        Some("image_bytes_oversize") => {
            let question = serde_json::json!({
                "type": "choice", "instructions": "Pick.", "criteria": {"a": "b"}
            });
            let raw = vec![0u8; 4 * 1024 * 1024 + 1];
            let encoded = base64::engine::general_purpose::STANDARD.encode(raw);
            let body = serde_json::json!({
                "model": "valen-preview-0923",
                "state": {"image": format!("data:image/png;base64,{encoded}")},
                "questions": {"q": question},
            });
            serde_json::to_vec(&body).unwrap()
        }
        _ => entry["body"].as_str().unwrap().as_bytes().to_vec(),
    }
}

/// The worker's processing pipeline up to (not including) execution. The
/// encoder is never reached by the rejection corpus.
struct NeverEncoder;
impl Encoder for NeverEncoder {
    fn segment(&self, _text: &str) -> Result<Vec<u32>, String> {
        panic!("the rejection corpus never tokenizes")
    }
}

fn run(
    raw: &[u8],
    special: &[String],
) -> Result<omni_valen_native::compile::Compiled, omni_valen_native::wire::RequestError> {
    let body = omni_valen_native::wire::parse_body(raw)?;
    let request = protocol::parse_request(&body, special)?;
    let prepared = preprocess::prepare(&request);
    Compiler::new(NeverEncoder, 8192).compile(&prepared)
}

#[test]
fn rejection_corpus_matches_the_reference_bodies() {
    let fixture = fixture();
    let special: Vec<String> = fixture["pins"]["special_tokens"]
        .as_array()
        .unwrap()
        .iter()
        .map(|t| t.as_str().unwrap().to_owned())
        .collect();
    for entry in fixture["rejections"].as_array().unwrap() {
        let name = entry["name"].as_str().unwrap();
        if name.starts_with("overflow_") {
            continue; // token counting needs the pinned tokenizer
        }
        let error = run(&rejection_body(entry), &special)
            .err()
            .unwrap_or_else(|| panic!("{name}: unexpectedly accepted"));
        assert_eq!(
            u64::from(error.status),
            entry["status"].as_u64().unwrap(),
            "{name}"
        );
        assert_eq!(error.message, entry["detail"].as_str().unwrap(), "{name}");
    }
}

