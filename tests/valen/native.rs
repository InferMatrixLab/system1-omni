//! Compiler-equivalence fixtures from the pinned reference
//! (recipe/valen/generate_native_fixtures.py), CPU-only, no weights needed:
//! the wire rejection corpus with the reference worker's exact error bodies,
//! and the tokenizer-free half of every valid case (state rendering, records,
//! grids, wire identity). Token-id equality needs the pinned tokenizer and
//! lives in native_tokenization.rs.

use std::io::Cursor;

use base64::Engine;
use serde_json::Value;

use omni_valen_native::compile::{Compiler, Encoder};
use omni_valen_native::preprocess::{self, RenderedState};
use omni_valen_native::protocol::{self, Kind, State};

fn fixture() -> Value {
    let path = format!(
        "{}/../../../../tests/valen/data/native_compiler.json",
        env!("CARGO_MANIFEST_DIR")
    );
    serde_json::from_str(&std::fs::read_to_string(path).unwrap()).unwrap()
}

fn png_url(width: u32, height: u32, colour: [u8; 3]) -> String {
    let image = image::RgbImage::from_pixel(width, height, image::Rgb(colour));
    let mut bytes = Vec::new();
    image
        .write_to(&mut Cursor::new(&mut bytes), image::ImageFormat::Png)
        .unwrap();
    format!(
        "data:image/png;base64,{}",
        base64::engine::general_purpose::STANDARD.encode(bytes)
    )
}

fn jpeg_url(width: u32, height: u32, colour: [u8; 3]) -> String {
    let image = image::RgbImage::from_pixel(width, height, image::Rgb(colour));
    let mut bytes = Vec::new();
    image
        .write_to(&mut Cursor::new(&mut bytes), image::ImageFormat::Jpeg)
        .unwrap();
    format!(
        "data:image/jpeg;base64,{}",
        base64::engine::general_purpose::STANDARD.encode(bytes)
    )
}

/// A case's request bytes: the recorded body, with generated images (only the
/// dimensions matter to the layout) regenerated by this side's encoder.
fn case_body(case: &Value) -> Vec<u8> {
    let mut body: Value = serde_json::from_str(case["body"].as_str().unwrap()).unwrap();
    if let Some(image) = case.get("image")
        && image["kind"] == "generated"
    {
        let size = image["size"].as_array().unwrap();
        let colour = image["colour"].as_array().unwrap();
        let rgb = [0, 1, 2].map(|i| colour[i].as_u64().unwrap() as u8);
        let url = if image["format"] == "png" {
            png_url(
                size[0].as_u64().unwrap() as u32,
                size[1].as_u64().unwrap() as u32,
                rgb,
            )
        } else {
            jpeg_url(
                size[0].as_u64().unwrap() as u32,
                size[1].as_u64().unwrap() as u32,
                rgb,
            )
        };
        body["state"]["image"] = Value::String(url);
        return serde_json::to_vec(&body).unwrap();
    }
    case["body"].as_str().unwrap().as_bytes().to_vec()
}

/// A rejection entry's request bytes.
fn rejection_body(entry: &Value) -> Vec<u8> {
    if let Some(encoded) = entry.get("body_b64") {
        return base64::engine::general_purpose::STANDARD
            .decode(encoded.as_str().unwrap())
            .unwrap();
    }
    match entry.get("synthesize").and_then(Value::as_str) {
        Some("body_oversize") => {
            let question = serde_json::json!({
                "type": "choice", "instructions": "Pick.", "criteria": {"a": "b"}
            });
            let body = serde_json::json!({
                "model": "valen-preview-0923",
                "state": "A".repeat(8 * 1024 * 1024 + 64),
                "questions": {"q": question},
            });
            serde_json::to_vec(&body).unwrap()
        }
        Some("image_encoded_oversize") => {
            let question = serde_json::json!({
                "type": "choice", "instructions": "Pick.", "criteria": {"a": "b"}
            });
            let encoded = "A".repeat(4 * (4usize * 1024 * 1024).div_ceil(3) + 1);
            let body = serde_json::json!({
                "model": "valen-preview-0923",
                "state": {"image": format!("data:image/png;base64,{encoded}")},
                "questions": {"q": question},
            });
            serde_json::to_vec(&body).unwrap()
        }
        Some("image_bytes_oversize") => {
            let question = serde_json::json!({
                "type": "choice", "instructions": "Pick.", "criteria": {"a": "b"}
            });
            let raw = vec![0u8; 4 * 1024 * 1024 + 1];
            let encoded = base64::engine::general_purpose::STANDARD.encode(raw);
            let body = serde_json::json!({
                "model": "valen-preview-0923",
                "state": {"image": format!("data:image/png;base64,{encoded}")},
                "questions": {"q": question},
            });
            serde_json::to_vec(&body).unwrap()
        }
        _ => entry["body"].as_str().unwrap().as_bytes().to_vec(),
    }
}

/// The worker's processing pipeline up to (not including) execution. The
/// encoder is never reached by the rejection corpus.
struct NeverEncoder;
impl Encoder for NeverEncoder {
    fn segment(&self, _text: &str) -> Result<Vec<u32>, String> {
        panic!("the rejection corpus never tokenizes")
    }
}

fn run(
    raw: &[u8],
    special: &[String],
) -> Result<omni_valen_native::compile::Compiled, omni_valen_native::wire::RequestError> {
    let body = omni_valen_native::wire::parse_body(raw)?;
    let request = protocol::parse_request(&body, special)?;
    let prepared = preprocess::prepare(&request);
    Compiler::new(NeverEncoder, 8192).compile(&prepared)
}

#[test]
fn rejection_corpus_matches_the_reference_bodies() {
    let fixture = fixture();
    let special: Vec<String> = fixture["pins"]["special_tokens"]
        .as_array()
        .unwrap()
        .iter()
        .map(|t| t.as_str().unwrap().to_owned())
        .collect();
    for entry in fixture["rejections"].as_array().unwrap() {
        let name = entry["name"].as_str().unwrap();
        if name.starts_with("overflow_") {
            continue; // token counting needs the pinned tokenizer
        }
        let error = run(&rejection_body(entry), &special)
            .err()
            .unwrap_or_else(|| panic!("{name}: unexpectedly accepted"));
        assert_eq!(
            u64::from(error.status),
            entry["status"].as_u64().unwrap(),
            "{name}"
        );
        assert_eq!(error.message, entry["detail"].as_str().unwrap(), "{name}");
    }
}

#[test]
fn default_special_tokens_still_reject_the_reserved_four() {
    // Without a tokenizer set the wire keeps the media-only defaults.
    let special = protocol::default_special_tokens();
    let body = br#"{"model":"valen-preview-0923","state":"<|image_pad|>","questions":{"q":{"type":"choice","instructions":"x","criteria":{"a":"b"}}}}"#;
    let error = run(body, &special).unwrap_err();
    assert_eq!(error.status, 422);
    assert_eq!(
        error.message,
        "state contains an unsupported tokenizer control token"
    );
}

#[test]
fn valid_cases_match_the_reference_preparation() {
    let fixture = fixture();
    for case in fixture["cases"].as_array().unwrap() {
        let name = case["name"].as_str().unwrap();
        let body = omni_valen_native::wire::parse_body(&case_body(case)).unwrap();
        let special: Vec<String> = fixture["pins"]["special_tokens"]
            .as_array()
            .unwrap()
            .iter()
            .map(|t| t.as_str().unwrap().to_owned())
            .collect();
        let request = protocol::parse_request(&body, &special).unwrap();
        let expected = &case["expected"];
        let state = &expected["state"];

        // The rendered state: user content after the template's trim, the
        // prompt text, and the image geometry after smart resize.
        let prepared = preprocess::prepare(&request);
        match (&prepared.state, state) {
            (
                RenderedState::Text {
                    user_content,
                    prompt,
                },
                state,
            ) => {
                assert_eq!(state["kind"], "text", "{name}");
                assert_eq!(
                    user_content,
                    state["user_content"].as_str().unwrap(),
                    "{name}"
                );
                assert_eq!(prompt, state["prompt"].as_str().unwrap(), "{name}");
            }
            (
                RenderedState::Image {
                    format,
                    width,
                    height,
                    grid_thw,
                    visual_tokens,
                    prompt,
                    ..
                },
                state,
            ) => {
                assert_eq!(state["kind"], "image", "{name}");
                assert_eq!(*format, state["format"].as_str().unwrap(), "{name}");
                assert_eq!(*width, state["width"].as_u64().unwrap() as usize, "{name}");
                assert_eq!(
                    *height,
                    state["height"].as_u64().unwrap() as usize,
                    "{name}"
                );
                assert_eq!(serde_json::json!(grid_thw), state["grid_thw"], "{name}");
                assert_eq!(
                    *visual_tokens,
                    state["visual_tokens"].as_u64().unwrap() as usize,
                    "{name}"
                );
                assert_eq!(prompt, state["prompt"].as_str().unwrap(), "{name}");
            }
        }

        // The question records and the compiled identity they carry.
        assert_eq!(
            prepared.questions.len(),
            expected["questions"].as_array().unwrap().len(),
            "{name}"
        );
        for (record, want) in prepared
            .questions
            .iter()
            .zip(expected["questions"].as_array().unwrap())
        {
            assert_eq!(record.qid, want["qid"].as_str().unwrap(), "{name}");
            assert_eq!(
                record.wire_kind.as_str(),
                want["wire_kind"].as_str().unwrap(),
                "{name}"
            );
            assert_eq!(
                record.record_kind.as_str(),
                want["record_kind"].as_str().unwrap(),
                "{name}"
            );
            assert_eq!(record.to_json(), want["record"], "{name} {}", record.qid);
        }

        // The wire identity the finisher needs survives preparation. The
        // candidate keys and descriptions are pinned through the records and
        // the compiled questions (native_tokenization.rs).
        for (question, want) in request
            .questions
            .iter()
            .zip(expected["questions"].as_array().unwrap())
        {
            assert_eq!(question.name, want["qid"].as_str().unwrap(), "{name}");
            let keys: Vec<&str> = want["keys"]
                .as_array()
                .unwrap()
                .iter()
                .map(|k| k.as_str().unwrap())
                .collect();
            assert_eq!(question.keys, keys, "{name}");
            assert_eq!(
                want["wire_kind"].as_str().unwrap(),
                match question.kind {
                    Kind::Choice => "choice",
                    Kind::Noul => "noul",
                    Kind::Score => "score",
                },
                "{name}"
            );
        }

        // An image state keeps its validated bytes and dimensions.
        if state["kind"] == "image" {
            let State::Image(image) = &request.state else {
                panic!("{name}: expected an image state");
            };
            assert!(image.width > 0 && image.height > 0, "{name}");
            assert!(!image.data.is_empty(), "{name}");
        }
    }
}

/// A deterministic encoder for layout-only tests: one id per character.
struct CharEncoder;
impl Encoder for CharEncoder {
    fn segment(&self, text: &str) -> Result<Vec<u32>, String> {
        Ok(text.chars().map(|c| c as u32).collect())
    }
}

#[test]
fn branch_layout_positions_and_budget_match_the_compiler_plan() {
    // Hand-computable plan mirroring the pinned compiler: the suffix is
    // "<|im_start|>user\n" (17 chars), the Task header, each candidate with
    // its key prefix, a newline each, then "Decision:".
    let body = omni_valen_native::wire::parse_body(
        br#"{"model":"valen-preview-0923","state":"s","questions":{"q":{"type":"choice","instructions":"I","criteria":{"a":"X","b":"YY"}}}}"#,
    )
    .unwrap();
    let request = protocol::parse_request(&body, &protocol::default_special_tokens()).unwrap();
    let prepared = preprocess::prepare(&request);
    let compiler = Compiler::new(CharEncoder, 1024);
    let compiled = compiler.compile(&prepared).unwrap();

    let prompt = "<|im_start|>user\ns<|im_end|>\n";
    let base_len = prompt.chars().count();
    let header = "Task: choice\nQuestion: I\nCandidates:\n".chars().count();
    let candidate_a = "a: X".chars().count();
    let candidate_b = "b: YY".chars().count();
    let q = &compiled.questions[0];
    assert_eq!(q.branches.len(), 1);
    let branch = &q.branches[0];
    assert_eq!(
        branch.length,
        base_len + 17 + header + candidate_a + 1 + candidate_b + 1 + "Decision:".len()
    );
    assert_eq!(
        branch.candidate_positions,
        vec![
            base_len + 17 + header + candidate_a - 1,
            base_len + 17 + header + candidate_a + 1 + candidate_b - 1
        ]
    );
    assert_eq!(branch.decision_position, branch.length - 1);
    assert_eq!(
        compiled.logical_tokens,
        base_len + 17 + header + candidate_a + 1 + candidate_b + 1 + "Decision:".len()
    );
    assert_eq!(compiled.compute_tokens, branch.length);

    // The budget: max_length rejects the first offending question's branch,
    // with the reference worker's exact wrapping.
    let base_overflow =
        base_len + 17 + header + candidate_a + 1 + candidate_b + 1 + "Decision:".len();
    let tight = Compiler::new(CharEncoder, base_overflow);
    let _ = tight.compile(&prepared).unwrap(); // exactly at the limit passes
    let over = Compiler::new(CharEncoder, base_overflow - 1);
    let error = over.compile(&prepared).unwrap_err();
    assert_eq!(error.status, 422);
    assert_eq!(
        error.message,
        format!(
            "request rejected by the pinned compiler: q: {base_overflow} tokens exceed \
             max_length={}; no truncation",
            base_overflow - 1
        )
    );

    // Score splits one branch per level, with no key prefix on candidates.
    let body = omni_valen_native::wire::parse_body(
        br#"{"model":"valen-preview-0923","state":"s","questions":{"g":{"type":"score","instructions":"I","criteria":["lo","hi"]}}}"#,
    )
    .unwrap();
    let request = protocol::parse_request(&body, &protocol::default_special_tokens()).unwrap();
    let prepared = preprocess::prepare(&request);
    let compiled = Compiler::new(CharEncoder, 1024).compile(&prepared).unwrap();
    let question = &compiled.questions[0];
    assert_eq!(question.branches.len(), 2);
    assert_eq!(question.keys, ["0", "1"]);
    assert_eq!(question.descriptions, ["lo", "hi"]);
    for branch in &question.branches {
        assert_eq!(branch.candidate_positions.len(), 1);
        assert_eq!(branch.decision_position, branch.length - 1);
    }
    assert_eq!(
        compiled.logical_tokens,
        base_len + 2 * (compiled.questions[0].branches[0].length - base_len)
    );
}
