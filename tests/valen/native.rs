#[test]
fn valid_cases_match_the_reference_preparation() {
    let fixture = fixture();
    for case in fixture["cases"].as_array().unwrap() {
        let name = case["name"].as_str().unwrap();
        let body = omni_valen_native::wire::parse_body(&case_body(case)).unwrap();
        let special: Vec<String> = fixture["pins"]["special_tokens"]
            .as_array()
            .unwrap()
            .iter()
            .map(|t| t.as_str().unwrap().to_owned())
            .collect();
        let request = protocol::parse_request(&body, &special).unwrap();
        let expected = &case["expected"];
        let state = &expected["state"];

        // The rendered state: user content after the template's trim, the
        // prompt text, and the image geometry after smart resize.
        let prepared = preprocess::prepare(&request);
        match (&prepared.state, state) {
            (
                RenderedState::Text {
                    user_content,
                    prompt,
                },
                state,
            ) => {
                assert_eq!(state["kind"], "text", "{name}");
                assert_eq!(
                    user_content,
                    state["user_content"].as_str().unwrap(),
                    "{name}"
                );
                assert_eq!(prompt, state["prompt"].as_str().unwrap(), "{name}");
            }
            (
                RenderedState::Image {
                    format,
                    width,
                    height,
                    grid_thw,
                    visual_tokens,
                    prompt,
                    ..
                },
                state,
            ) => {
                assert_eq!(state["kind"], "image", "{name}");
                assert_eq!(*format, state["format"].as_str().unwrap(), "{name}");
                assert_eq!(*width, state["width"].as_u64().unwrap() as usize, "{name}");
                assert_eq!(
                    *height,
                    state["height"].as_u64().unwrap() as usize,
                    "{name}"
                );
                assert_eq!(serde_json::json!(grid_thw), state["grid_thw"], "{name}");
                assert_eq!(
                    *visual_tokens,
                    state["visual_tokens"].as_u64().unwrap() as usize,
                    "{name}"
                );
                assert_eq!(prompt, state["prompt"].as_str().unwrap(), "{name}");
            }
        }

        // The question records and the compiled identity they carry.
        assert_eq!(
            prepared.questions.len(),
            expected["questions"].as_array().unwrap().len(),
            "{name}"
        );
        for (record, want) in prepared
            .questions
            .iter()
            .zip(expected["questions"].as_array().unwrap())
        {
            assert_eq!(record.qid, want["qid"].as_str().unwrap(), "{name}");
            assert_eq!(
                record.wire_kind.as_str(),
                want["wire_kind"].as_str().unwrap(),
                "{name}"
            );
            assert_eq!(
                record.record_kind.as_str(),
                want["record_kind"].as_str().unwrap(),
                "{name}"
            );
            assert_eq!(record.to_json(), want["record"], "{name} {}", record.qid);
        }

        // The wire identity the finisher needs survives preparation. The
        // candidate keys and descriptions are pinned through the records and
        // the compiled questions (native_tokenization.rs).
        for (question, want) in request
            .questions
            .iter()
            .zip(expected["questions"].as_array().unwrap())
        {
            assert_eq!(question.name, want["qid"].as_str().unwrap(), "{name}");
            let keys: Vec<&str> = want["keys"]
                .as_array()
                .unwrap()
                .iter()
                .map(|k| k.as_str().unwrap())
                .collect();
            assert_eq!(question.keys, keys, "{name}");
            assert_eq!(
                want["wire_kind"].as_str().unwrap(),
                match question.kind {
                    Kind::Choice => "choice",
                    Kind::Noul => "noul",
                    Kind::Score => "score",
                },
                "{name}"
            );
        }

        // An image state keeps its validated bytes and dimensions.
        if state["kind"] == "image" {
            let State::Image(image) = &request.state else {
                panic!("{name}: expected an image state");
            };
            assert!(image.width > 0 && image.height > 0, "{name}");
            assert!(!image.data.is_empty(), "{name}");
        }
    }
}

/// A deterministic encoder for layout-only tests: one id per character.
struct CharEncoder;
impl Encoder for CharEncoder {
    fn segment(&self, text: &str) -> Result<Vec<u32>, String> {
        Ok(text.chars().map(|c| c as u32).collect())
    }
}

#[test]
fn branch_layout_positions_and_budget_match_the_compiler_plan() {
    // Hand-computable plan mirroring the pinned compiler: the suffix is
    // "<|im_start|>user\n" (17 chars), the Task header, each candidate with
    // its key prefix, a newline each, then "Decision:".
    let body = omni_valen_native::wire::parse_body(
        br#"{"model":"valen-preview-0923","state":"s","questions":{"q":{"type":"choice","instructions":"I","criteria":{"a":"X","b":"YY"}}}}"#,
    )
    .unwrap();
    let request = protocol::parse_request(&body, &protocol::default_special_tokens()).unwrap();
    let prepared = preprocess::prepare(&request);
    let compiler = Compiler::new(CharEncoder, 1024);
    let compiled = compiler.compile(&prepared).unwrap();

    let prompt = "<|im_start|>user\ns<|im_end|>\n";
    let base_len = prompt.chars().count();
    let header = "Task: choice\nQuestion: I\nCandidates:\n".chars().count();
    let candidate_a = "a: X".chars().count();
    let candidate_b = "b: YY".chars().count();
    let q = &compiled.questions[0];
    assert_eq!(q.branches.len(), 1);
    let branch = &q.branches[0];
    assert_eq!(
        branch.length,
        base_len + 17 + header + candidate_a + 1 + candidate_b + 1 + "Decision:".len()
    );
    assert_eq!(
        branch.candidate_positions,
        vec![
            base_len + 17 + header + candidate_a - 1,
            base_len + 17 + header + candidate_a + 1 + candidate_b - 1
        ]
    );
    assert_eq!(branch.decision_position, branch.length - 1);
    assert_eq!(
        compiled.logical_tokens,
        base_len + 17 + header + candidate_a + 1 + candidate_b + 1 + "Decision:".len()
    );
    assert_eq!(compiled.compute_tokens, branch.length);

    // The budget: max_length rejects the first offending question's branch,
    // with the reference worker's exact wrapping.
    let base_overflow =
        base_len + 17 + header + candidate_a + 1 + candidate_b + 1 + "Decision:".len();
    let tight = Compiler::new(CharEncoder, base_overflow);
    let _ = tight.compile(&prepared).unwrap(); // exactly at the limit passes
    let over = Compiler::new(CharEncoder, base_overflow - 1);
    let error = over.compile(&prepared).unwrap_err();
    assert_eq!(error.status, 422);
    assert_eq!(
        error.message,
        format!(
            "request rejected by the pinned compiler: q: {base_overflow} tokens exceed \
             max_length={}; no truncation",
            base_overflow - 1
        )
    );

    // Score splits one branch per level, with no key prefix on candidates.
    let body = omni_valen_native::wire::parse_body(
        br#"{"model":"valen-preview-0923","state":"s","questions":{"g":{"type":"score","instructions":"I","criteria":["lo","hi"]}}}"#,
    )
    .unwrap();
    let request = protocol::parse_request(&body, &protocol::default_special_tokens()).unwrap();
    let prepared = preprocess::prepare(&request);
    let compiled = Compiler::new(CharEncoder, 1024).compile(&prepared).unwrap();
    let question = &compiled.questions[0];
    assert_eq!(question.branches.len(), 2);
    assert_eq!(question.keys, ["0", "1"]);
    assert_eq!(question.descriptions, ["lo", "hi"]);
    for branch in &question.branches {
        assert_eq!(branch.candidate_positions.len(), 1);
        assert_eq!(branch.decision_position, branch.length - 1);
    }
    assert_eq!(
        compiled.logical_tokens,
        base_len + 2 * (compiled.questions[0].branches[0].length - base_len)
    );
}

